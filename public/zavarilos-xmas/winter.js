export function newCardLayout() {
  const layout = originalLayout();
  layout.background = '#892329';
  for (const layer of layout.layers) {
    if (layer.id === 'logo') layer.color = '#234b3b';
    if (layer.id === 'meta') layer.text = 'ЛИЦЕЙ / НОВОГОДНИЙ ВЫПУСК';
    if (layer.id === 'tagline') {
      Object.assign(layer, {visible:true, text:'новогодние предсказания', y:20, size:40});
    }
  }
  return layout;
}

export function shareUrl(sign) {
  const index = signs.findIndex(([title]) => title === sign.title);
  return index < 0 ? home : home + 's/' + String(index + 1).padStart(2,'0') + '/';
}

export function shareCaption(sign) {
  return 'У меня заварилось новогоднее предсказание. А у тебя?\n' + shareUrl(sign);
}

export function shareCaptionHtml(sign) {
  return '<p>У меня заварилось новогоднее предсказание. <a href="' + shareUrl(sign) + '">А у тебя?</a></p>';
}
